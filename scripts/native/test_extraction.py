"""Model-free tests for native/Extraction.swift: PDF text and Vision OCR.

Fixtures are generated by the harness itself: a text-layer PDF, a scanned PDF
whose pages carry pixels and no text layer, a blank page, a rotated scan, and a
page-ceiling document. Extraction uses PDFKit and Vision only, so no model, no
session and no prompt is involved anywhere in this file.

Vision's exact output for a synthetic line is stable on this SDK but is still an
OCR result; the scanned-page cases assert the recognized words rather than byte
equality, and the text-layer cases assert exact bytes.
"""
import os
import shutil
import tempfile
import unittest
from pathlib import Path

import helper_protocol as protocol

PHRASE = 'Banana bread recipe'


class ExtractionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not protocol.can_execute():
            raise unittest.SkipTest(
                'PDFKit and Vision extraction requires Apple silicon macOS 27')
        cls.folder = Path(tempfile.mkdtemp(prefix='hollis-extraction-'))
        cls.addClassCleanup(shutil.rmtree, cls.folder, True)
        cls.harness = protocol.build_extraction_harness(cls.folder)

    def fixture(self, mode, name, *args):
        path = self.folder / name
        answer = protocol.harness(self.harness, mode, str(path), *args)
        self.assertTrue(answer.get('ok'), answer)
        return path

    def test_text_layer_is_extracted_exactly_and_marked_text(self):
        path = self.fixture('make-text-pdf', 'text.pdf', '2', 'Alpha beta gamma.')
        answer = protocol.harness(self.harness, 'extract', str(path))
        self.assertTrue(answer['ok'], answer)
        self.assertEqual(answer['media'], 'pdf')
        self.assertEqual(answer['page_count'], 2)
        self.assertEqual([page['page'] for page in answer['pages']], [1, 2])
        for page in answer['pages']:
            self.assertEqual(page['method'], 'text')
            self.assertEqual(page['text'], f"Page {page['page']}\nAlpha beta gamma.")
        self.assertEqual(answer['text_bytes'],
                         sum(len(page['text'].encode()) for page in answer['pages']))

    def test_page_selection_extracts_only_the_requested_pages(self):
        path = self.fixture('make-text-pdf', 'select.pdf', '4', 'Selected page text.')
        answer = protocol.harness(self.harness, 'extract', str(path), '4,2,2')
        self.assertTrue(answer['ok'], answer)
        self.assertEqual(answer['page_count'], 4)
        self.assertEqual([page['page'] for page in answer['pages']], [2, 4])

    def test_scanned_page_is_recognized_and_marked_ocr(self):
        path = self.fixture('make-scan-pdf', 'scan.pdf', '1', PHRASE)
        answer = protocol.harness(self.harness, 'extract', str(path))
        self.assertTrue(answer['ok'], answer)
        self.assertEqual(len(answer['pages']), 1)
        page = answer['pages'][0]
        self.assertEqual(page['method'], 'ocr')
        self.assertIn(PHRASE.lower(), page['text'].lower())
        # A page with pixels and no text layer must never claim a text layer.
        self.assertTrue(page['text'].strip())

    def test_rotated_scanned_page_is_recognized(self):
        path = self.fixture('make-rotated-pdf', 'rotated.pdf', 'Rotated scan text')
        answer = protocol.harness(self.harness, 'extract', str(path))
        self.assertTrue(answer['ok'], answer)
        page = answer['pages'][0]
        self.assertEqual(page['method'], 'ocr')
        self.assertIn('rotated', page['text'].lower())

    def test_blank_page_reports_no_text_not_an_empty_success(self):
        path = self.fixture('make-blank-pdf', 'blank.pdf')
        answer = protocol.harness(self.harness, 'extract', str(path))
        self.assertEqual(answer, {'ok': False, 'failure': 'extract_no_text'})

    def test_page_ceiling_reports_the_measured_page_count(self):
        path = self.fixture('make-text-pdf', 'many.pdf', '2001', 'Page ceiling.')
        answer = protocol.harness(self.harness, 'extract', str(path),
                                  timeout=1200)
        self.assertFalse(answer['ok'])
        self.assertEqual(answer['failure'], 'invalid_document')
        self.assertEqual(answer['limit'], 2000)
        self.assertEqual(answer['actual'], 2001)

    def test_text_ceiling_reports_bytes_produced_and_the_page(self):
        line = 'word ' * 16  # 80 bytes per line, 40 lines per page
        path = self.fixture('make-long-pdf', 'long.pdf', '45', '40', line)
        answer = protocol.harness(self.harness, 'extract', str(path),
                                  timeout=1200)
        self.assertFalse(answer['ok'])
        self.assertEqual(answer['failure'], 'context_capacity')
        self.assertEqual(answer['limit'], 131072)
        self.assertGreater(answer['actual'], answer['limit'])
        self.assertGreaterEqual(answer['page'], 40)
        self.assertLessEqual(answer['page'], 45)

    def test_requested_page_beyond_the_document_is_refused_with_numbers(self):
        path = self.fixture('make-text-pdf', 'short.pdf', '2', 'Two pages only.')
        answer = protocol.harness(self.harness, 'extract', str(path), '3')
        self.assertEqual(answer, {'ok': False, 'failure': 'page_out_of_range',
                                  'page': 3, 'page_count': 2})

    def test_non_pdf_content_is_unsupported_media(self):
        text = self.folder / 'notes.txt'
        text.write_text('plain text is the Go side\'s job\n')
        answer = protocol.harness(self.harness, 'extract', str(text))
        self.assertEqual(answer, {'ok': False, 'failure': 'unsupported_media'})
        png = self.folder / 'image.png'
        png.write_bytes(b'\x89PNG\r\n\x1a\n' + b'\x00' * 32)
        answer = protocol.harness(self.harness, 'extract', str(png))
        self.assertEqual(answer, {'ok': False, 'failure': 'unsupported_media'})

    def test_symlink_is_not_followed(self):
        target = self.fixture('make-text-pdf', 'target.pdf', '1', 'Never reached.')
        link = self.folder / 'link.pdf'
        link.symlink_to(target)
        answer = protocol.harness(self.harness, 'extract', str(link))
        self.assertEqual(answer, {'ok': False, 'failure': 'invalid_document'})

    def test_fifo_does_not_block_and_is_refused(self):
        fifo = self.folder / 'pipe.pdf'
        os.mkfifo(fifo)
        # No writer: a blocking open would hang the harness, so the call has a
        # short timeout and the refusal must arrive well inside it.
        answer = protocol.harness(self.harness, 'extract', str(fifo), timeout=20)
        self.assertEqual(answer, {'ok': False, 'failure': 'invalid_document'})

    def test_file_ceiling_is_reported_before_reading(self):
        large = self.folder / 'large.pdf'
        with large.open('wb') as stream:
            stream.truncate(64 * 1024 * 1024 + 1)
        answer = protocol.harness(self.harness, 'extract', str(large))
        self.assertFalse(answer['ok'])
        self.assertEqual(answer['failure'], 'invalid_document')
        self.assertEqual(answer['limit'], 64 * 1024 * 1024)
        self.assertEqual(answer['actual'], 64 * 1024 * 1024 + 1)

    def test_missing_file_is_refused_without_a_path(self):
        answer = protocol.harness(self.harness, 'extract',
                                  str(self.folder / 'absent.pdf'))
        self.assertEqual(answer, {'ok': False, 'failure': 'invalid_document'})


if __name__ == '__main__':
    unittest.main()
